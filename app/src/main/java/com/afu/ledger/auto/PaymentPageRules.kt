package com.afu.ledger.auto

/**
 * 支付页面识别规则。
 *
 * 全部集中在这里：微信/支付宝改版时只改本文件，不散落到 Service 或 UI。
 * 用「文本特征」而不是 resource-id —— 两家应用的控件 id 不对外稳定。
 */
object PaymentPageRules {

    const val WECHAT_PACKAGE = "com.tencent.mm"
    const val ALIPAY_PACKAGE = "com.eg.android.AlipayGphone"

    val supportedPackages: Set<String> = setOf(WECHAT_PACKAGE, ALIPAY_PACKAGE)

    /** 支付结果页特征词（强特征：出现即认为是支付结果页）。 */
    val resultKeywords: List<String> = listOf(
        "支付成功",
        "付款成功",
        "交易成功",
        "已支付",
        "支付完成",
        "付款完成",
    )

    /** 账单详情页特征词（强特征）。 */
    val billKeywords: List<String> = listOf(
        "账单详情",
        "余额明细详情",
        "交易详情",
        "交易单号",
        "商户单号",
        "商家订单号",
        "账单分类",
    )

    /**
     * 交易类通用特征词（弱特征）。
     *
     * ## 为什么需要这一层
     *
     * 原先只认「支付成功」「账单详情」这类**页面标题**特征词。真实页面实测发现覆盖不住：
     * 支付宝的「余额明细详情」页有金额、有交易号，标题却既不是「支付成功」也不是
     * 「账单详情」，于是整页被判定为非支付页（`miss NOT_PAYMENT_PAGE`）。
     * 这类详情页在支付宝里很常见（扫码付、转账、自动扣款都走它）。
     *
     * 同赛道的 Tally（`cypressincloud/Tally`）的做法给了启发：
     * 它**不要求页面标题匹配**，而是「找到金额候选 + 命中交易类关键词」就认为有效，
     * 再用关键词权重打分来降低误报。
     *
     * 这里采纳同样的思路，但**保留本项目更严格的安全底线**：
     * 金额必须唯一（见 [PaymentPageDetector]）。Tally 是「多金额时选评分最高的一个」，
     * 我们坚持「有歧义就放弃，宁可漏记也不记错」。
     *
     * 命中条件：强特征任一命中，**或** 弱特征命中 [MIN_TRADE_KEYWORD_HITS] 个。
     */
    val tradeKeywords: List<String> = listOf(
        "交易", "订单", "金额", "实付", "合计", "总计",
        "收款", "到账", "支付方式", "付款方式", "商品说明",
        "交易类型", "对方账户", "清算机构", "收单机构",
    )

    /** 弱特征命中多少个才认为「这确实是交易类页面」。 */
    const val MIN_TRADE_KEYWORD_HITS = 2

    /**
     * 命中任意一个就放弃识别。
     *
     * ## 这些词要「足够具体」
     *
     * 真实页面实测教训：最初这里写的是「退款」，结果支付宝**账单列表页**顶部的
     * 筛选标签里就有「退款」两个字，整页被判为非支付页（`miss EXCLUDED_KEYWORD`）。
     * 同理「已关闭」「已取消」也会出现在列表里某一笔的状态文案上。
     *
     * 所以排除词必须是**指向这一笔交易状态**的完整表述，
     * 不能用「只是出现了某个词」就否掉整页 —— 页面顶部/底部的按钮与筛选标签
     * 会和当前这笔交易混在一起。
     */
    val excludedKeywords: List<String> = listOf(
        "待支付",
        "待付款",
        "确认付款",
        "立即支付",
        "去支付",
        "将于",          // 「将于明日扣款」这类未来时态
        "预计扣款",
        // 注意：不要用单独的「退款」。改为指向退款结果的表述。
        "退款成功",
        "已退款",
        "退款已到账",
        "交易关闭",
        "收款到账",
        "已收款",
    )

    /**
     * 主界面 / 列表页的**独有**导航词。
     *
     * ## 为什么需要这一层
     *
     * 真实页面实测发现：支付宝**首页**的「最近消息」区会列出历史通知文本，
     * 例如「天猫 / 付款成功 / ¥25.00」。节点采集把这些文本读进来后，
     * 页面判定看到了「付款成功」+ 金额，就误判成支付结果页并弹出确认卡片，
     * 商户名还会取到页面上的搜索框占位文字（实测取到了「公积金查询」）。
     *
     * ## 词表必须「只在主界面出现」
     *
     * 这里踩过一次坑：最初把「更多」「出行」「转账」也放进来，
     * 结果**支付宝账单详情页也识别不了了** —— 账单页里同样会出现这些词
     * （「查看更多」「转账」这类常见文案），两个一凑就达到阈值，整页被误杀。
     *
     * 所以只保留「只在主界面才有、账单类页面不会出现」的专有入口：
     * 扫一扫 / 收付款 / 卡包 / 市民中心 / 余额宝 是支付宝首页的固定九宫格；
     * 通讯录 / 发现 是微信底栏。
     *
     * 阈值取 3：宁可漏掉一次首页误判，也绝不能误杀真实支付页。
     */
    val mainScreenKeywords: List<String> = listOf(
        // 支付宝首页九宫格专有入口
        "扫一扫", "收付款", "卡包", "市民中心", "余额宝",
        // 微信底栏
        "通讯录", "发现",
    )

    /** 命中多少个主界面导航词才认定为「这是主界面/列表页」。 */
    const val MIN_MAIN_SCREEN_HITS = 3
}

package com.afu.ledger.auto

/**
 * 支付/账单页面识别规则。
 *
 * 全部集中在这里：微信/支付宝改版时只改本文件，不散落到 Service 或 UI。
 * 用「文本特征」而不是 resource-id —— 两家应用的控件 id 不对外稳定。
 *
 * ## 判定顺序（不可调换）
 *
 * 1. **强排除**：指向「另一笔交易」的状态词（待支付、已关闭…）
 * 2. **列表页**：词表 + 多行日期时间
 * 3. **主界面 / 我的页**（辅助，不再是唯一防线）
 * 4. **正向准入**：必须是账单详情页 —— 有标题，或有 ≥2 个专属字段
 * 5. **金额与方向**：见 [AmountParser]
 *
 * 顺序错了就会重演两次真实事故：支付宝首页「最近消息」里的历史通知被当成支付结果页；
 * 支付宝「我的」页的广告文案被当成商户名。
 *
 * ## 为什么第 4 步是「正向准入」
 *
 * 旧实现只有负向排除：只要没命中主界面入口词，剩下的页面就放行。词表漏一个就穿过去，
 * 而支付宝的二级页面、活动页、小程序页无穷无尽，词表永远追不完。
 * 现在要求页面**自己证明**它是账单详情页，漏词不再等于误触发。
 */
object PaymentPageRules {

    const val WECHAT_PACKAGE = "com.tencent.mm"
    const val ALIPAY_PACKAGE = "com.eg.android.AlipayGphone"

    val supportedPackages: Set<String> = setOf(WECHAT_PACKAGE, ALIPAY_PACKAGE)

    /** 来源应用的人话名字，用于悬浮窗与日志。 */
    fun sourceLabel(packageName: String): String = when (packageName) {
        WECHAT_PACKAGE -> "微信"
        ALIPAY_PACKAGE -> "支付宝"
        else -> packageName
    }

    /**
     * 账单详情页的标题类特征。
     *
     * 命中任意一个即可认定为账单详情页 —— 这类词**只作为页面标题**出现，
     * 不会出现在首页、列表页或聊天页里。
     */
    val billTitleKeywords: List<String> = listOf(
        "账单详情",
        "交易详情",
        "余额明细详情",
        "账单明细",
        "订单详情",
        "交易记录详情",
        "转账详情",
    )

    /**
     * 账单详情页的**专属字段**。
     *
     * 命中 [MIN_BILL_FIELD_HITS] 个即认定是账单详情页。
     *
     * 已按真机样本覆盖两套支付宝布局与微信各类型：
     * - 支付宝旧版：支付时间 / 付款方式 / 商品说明 / 收单机构 / 清算机构 / 收款方全称 / 账单分类
     * - 支付宝新版：当前状态 / 支付时间 / 商品 / 商户全称 / 收单机构 / 支付方式 / 交易单号 / 商户单号
     * - 微信支付：当前状态 / 支付时间 / 商品 / 商户全称 / 收单机构 / 支付方式 / 交易单号 / 商户单号
     * - 微信红包：当前状态 / 红包详情 / 收款时间 / 交易单号 / 商户单号
     * - 微信转账：当前状态 / 转账说明 / 转账时间 / 收款时间 / 转账单号
     *
     * **`转账单号` 不能漏**：微信的转账类账单只用这个标签，漏了它转账页就凑不够证据。
     */
    val billStrongFields: List<String> = listOf(
        "交易单号",
        "商戶单号",
        "商户单号",
        "商家订单号",
        "转账单号",
        "收单机构",
        "清算机构",
        "账单分类",
        "对方账户",
        "商品说明",
        "交易类型",
        "账单服务",
        "商家小程序",
        "收款方",
        "付款方",
        "收款方全称",
        "商户全称",
        "转账说明",
        "红包详情",
        "当前状态",
        "支付方式",
        "付款方式",
        "商品",
        "创建时间",
        "支付时间",
        "收款时间",
        "转账时间",
    )

    /** 命中多少个账单专属字段才认定为账单详情页。 */
    const val MIN_BILL_FIELD_HITS = 2

    /**
     * 支付结果页特征词。
     *
     * 结果页**参与识别**（见 [PaymentPageDetector]）：页面命中成功状态词、又没有账单标题、
     * 没有交易单号、没有账单时间字段时，判为结果页并产出草稿。同一笔随后出现在账单详情页时，
     * 由会话去重（同包名 + 同金额 + 同方向 + 时间窗）挡住第二次弹窗。
     */
    val resultKeywords: List<String> = listOf(
        "支付成功",
        "付款成功",
        "交易成功",
        "已支付",
        "支付完成",
        "付款完成",
    )

    /** 状态词 → 收入。用于金额自身没有方向信息时的兜底判断。 */
    val incomeStatusKeywords: List<String> = listOf(
        "退款成功",
        "已退款",
        "退款已到账",
        "已到账",
        "已存入零钱",
        "收款到账",
        "已收款",
    )

    /** 状态词 → 支出。 */
    val expenseStatusKeywords: List<String> = listOf(
        "支付成功",
        "付款成功",
        "交易成功",
        "已支付",
        "支付完成",
        "付款完成",
        // 转账转出：微信转账成功后停在「转账成功 / 已存入对方零钱」页。
        "转账成功",
        "已转账",
    )

    /**
     * 红包 / 转账类结果页的**场景标识词**。
     *
     * 只有页面上出现这些词，才会把「已存入零钱 / 已收款」之类的状态词当成一笔交易。
     * 没有这道限定，「零钱充值成功 → 已存入零钱」「理财收益已到账」都会被记成收入。
     */
    val transferSceneKeywords: List<String> = listOf(
        "红包",
        "转账",
        "已收款",
    )

    /**
     * 红包 / 转账类结果页 → 收入。
     *
     * 真机文案：收红包后是「已存入零钱」，收款方转账页是「已收款」。
     */
    val incomeResultKeywords: List<String> = listOf(
        "已存入零钱",
        "已收款",
        "收款到账",
        "已到账",
    )

    /**
     * 红包 / 转账类结果页 → 支出。
     *
     * 转出方停在「转账成功 / 已存入对方零钱」页时只有这个状态词，
     * 金额通常是不带符号的 `¥100.00`，方向只能由它给出。
     */
    val outgoingTransferKeywords: List<String> = listOf(
        "转账成功",
        "已转账",
        "已存入对方零钱",
    )

    /**
     * 命中任意一个就放弃识别。
     *
     * 这些词必须**指向这一笔交易的状态**，不能用「页面出现了某个词」就否掉整页：
     * 列表页顶部的筛选标签、按钮文案会和当前这笔交易混在一起。
     */
    val excludedKeywords: List<String> = listOf(
        "待支付",
        "待付款",
        "确认付款",
        "立即支付",
        "去支付",
        "将于",          // 「将于明日扣款」这类未来时态
        "预计扣款",
        // 不要用单独的「退款」：账单列表页的筛选标签里就有「退款」，退款账单页也有。
        "交易关闭",
    )

    /**
     * 主界面 / 我的页的**专有入口词**（辅助判据）。
     *
     * 命中 [MIN_HOME_SCREEN_HITS] 个即排除。要求组合命中而不是单词命中，
     * 是因为「余额」「账单」这类词在账单详情页里也会出现。
     */
    val homeOrMyKeywords: List<String> = listOf(
        "扫一扫", "收付款", "卡包", "市民中心", "余额宝",
        "总资产", "支付宝会员", "最近消息",
        "通讯录", "发现", "朋友圈", "收藏", "表情",
    )

    /** 命中多少个主界面/我的页入口词才排除整页。 */
    const val MIN_HOME_SCREEN_HITS = 2

    /**
     * 列表页特征词。
     *
     * 账单列表页的专属文案：顶部筛选、查找入口、统计入口、月份标题。
     */
    val listPageKeywords: List<String> = listOf(
        "全部账单",
        "查找交易",
        "收支统计",
        "收支分析",
        "月账单",
        "账单列表",
        "交易记录",
        "按时间筛选",
        "全部交易",
        "搜索交易记录",
    )

    /** 命中多少个列表页特征词才排除整页。 */
    const val MIN_LIST_PAGE_HITS = 2

    /**
     * 支付结果页的文本行数上限。
     *
     * 结果页都是「一屏说清一笔」的短页面（真机微信支付成功页 OCR 出 9–12 行，含状态栏）。
     * 聊天记录与公众号文章能被 OCR 读成几十行，里面恰好出现「支付成功 ¥25.50」时，
     * 只靠状态词加金额就会误弹窗 —— 行数上限是这里最便宜的防线。
     */
    const val MAX_RESULT_PAGE_LINES = 20

    /**
     * 聊天 / 内容流特征词。
     *
     * 微信聊天页底部固定有「按住 说话」「语音输入」这类输入栏文案，公众号文章带「在看」「阅读原文」。
     * 这些词**不会**出现在支付结果页上，命中任一即说明当前页面不是结果页：
     * 聊天里别人发来的「支付成功 ¥25.50」截图、文章里的收款文案都在这里被拦住。
     */
    val chatOrFeedKeywords: List<String> = listOf(
        "按住 说话",
        "按住说话",
        "发送消息",
        "聊天信息",
        "语音输入",
        "朋友圈",
        "文件传输助手",
        "阅读原文",
        "在看",
    )

    /**
     * 聊天**输入栏**证据。命中级即认定是聊天页，直接跳过识别。
     *
     * 匹配前会去掉全部空白（见 [containsChatEvidence]）：OCR 对「按住 说话」的空格很不稳定，
     * 真机读成过「按住说话」和「按住 说 话」两种，按原样比较会漏。
     */
    val chatInputBarKeywords: List<String> = listOf(
        "按住说话",
        "按住讲话",
        "语音输入",
        "发送消息",
        "聊天信息",
        "文件传输助手",
    )

    /**
     * 聊天**卡片 / 会话行为**证据。
     *
     * 微信聊天里的转账卡片会写「转账给 xxx」，收款/撤回/正在输入这类文案更是只有聊天页才有。
     *
     * **不要把「微信红包」「微信转账」放进这里**：微信红包领取页自己就写着「微信红包」，
     * 放进来会把真实的红包账单页误杀（真机回归用例当场就挂）。
     *
     * 这类词在真正的转账账单详情页里也可能出现（「转账给」），所以判定时留了例外：
     * 页面同时命中 ≥ [MIN_BILL_FIELD_HITS] 个账单强字段时不算聊天页。
     */
    val chatCardKeywords: List<String> = listOf(
        "转账给",
        "消息已发出",
        "对方正在输入",
        "撤回了一条消息",
        "拍一拍",
        "[动画表情]",
        "语音通话",
        "视频通话",
    )

    /**
     * 微信公众号会话页的底部菜单。
     *
     * 「微信支付」这个服务号会把自己的消费记录按时间堆在会话里，每条都是**大字金额**+「账单详情」，
     * 长得和支付结果页几乎一样（真机就是这样把 27.00 读成 2700 弹了一张卡片）。
     * 唯一稳定的区别是它底部挂着公众号的自定义菜单：「我的账单」「支付服务」「优惠」。
     * 支付结果页没有这组菜单。
     */
    val wechatPayConversationKeywords: List<String> = listOf(
        "我的账单",
        "支付服务",
    )

    /** 去掉全部空白：OCR 的空格位置不可靠，比较前统一抹平。 */
    fun normalizeForMatch(text: String): String = text.filterNot { it.isWhitespace() }

    /** 页面里是否有聊天 / 会话页证据。 */
    fun containsChatEvidence(pageText: String): Boolean {
        val normalized = normalizeForMatch(pageText)
        return chatInputBarKeywords.any { normalized.contains(normalizeForMatch(it)) } ||
            chatCardKeywords.any { normalized.contains(normalizeForMatch(it)) }
    }

    /**
     * 一页里出现多少行「日期 + 时间」就认定这是列表页。
     *
     * 真实微信账单列表每一条交易都带「10月18日 20:10」这样的时间；
     * 而账单详情页只有**一行**「支付时间 2026年10月18日 20:10:02」。
     */
    const val LIST_PAGE_MIN_TIMESTAMP_LINES = 3

    /** 日期 + 时间的行特征。 */
    val timestampLinePattern: Regex = Regex(
        """(\d{1,2}月\d{1,2}日|\d{4}年\d{1,2}月\d{1,2}日|\d{1,4}[-/]\d{1,2}[-/]\d{1,2})""",
    )

    /**
     * 只有时分的时间，如 `14:58`。
     *
     * 微信**会话列表**每一行右侧都是这种时间，而且没有日期 —— 上面那条「日期+时间」判据抓不到它，
     * 于是会话列表被当成「支付结果页」放行（真机：会话列表里「微信支付 · 已支付¥27.00」那一行
     * 提供状态词与金额，弹了一张卡片）。
     */
    val clockOnlyPattern: Regex = Regex("""(?:^|[^\d:])\d{1,2}:\d{2}(?:[^\d:]|$)""")

    /** 一页里出现多少行纯时分时间就认定是会话 / 列表页。 */
    const val CLOCK_LINES_MIN = 3

    /**
     * 交易单号字段的标签。
     *
     * `转账单号` 是微信转账类账单专用的，漏掉它会让转账页全部退化成低精度指纹。
     */
    val tradeNoLabels: List<String> = listOf(
        "交易单号",
        "商户单号",
        "商戶单号",
        "商家订单号",
        "转账单号",
        "订单号",
    )

    /** 商户字段的标签，按可信度排序。 */
    val merchantLabels: List<String> = listOf(
        "收款方全称",
        "商户全称",
        "收款方",
        "商户名称",
        "商家名称",
        "对方账户",
    )
}
